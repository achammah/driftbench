/**
 * Writes docs/reference/blame.md from the code: every evidence name a blame or placement rule can read, with
 * its cost class, its values and what it is computed from (packages/core/src/evidence).
 *
 * Usage:  tsx tools/docs/blame-reference.ts [--check]
 *   (no flag)   write the page
 *   --check     compare instead of writing: exit 1 when the page is stale
 * Exit:   0 written or current; 1 stale; 2 usage error.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { EVIDENCE_PROVIDERS } from '../../packages/core/src/evidence';

const ROOT = fileURLToPath(new URL('../..', import.meta.url));
export const BLAME_OUT = resolve(ROOT, 'docs/reference/blame.md');

const COST_LINE: Record<string, string> = {
  static: 'read from the stored run and the estate map; no agent call',
  judge: 'a stored answer of a calibrated judge; replayed, never called by blame',
  run: 'an agent run, made only by `diagnostic/liability-confirm` within its budget, and read once stored',
};

function cell(text: string): string {
  return text.replace(/\|/g, '\\|').replace(/\n/g, ' ');
}

/** The page, from the code. */
export function renderBlameReference(): string {
  const lines: string[] = [
    '<!-- Generated by tools/docs/blame-reference.ts from the code. Do not edit by hand. -->',
    '',
    '# Blame, placement and diagnostics reference',
    '',
    'A failing block gets two answers besides its machine verdict: who made the mistake (`policy/blame`) and where one change stops it recurring (`policy/placement`). Both are rule files that read named evidence and never compute it. This page lists every name, generated from the code.',
    '',
    '## Evidence names',
    '',
    `Every name is computed once by one provider, from what the run, the estate map, the value check and any confirm run stored. A name whose value is unknown is left out, so a condition on it never holds. ${EVIDENCE_PROVIDERS.length} names ship.`,
    '',
    '| Cost class | Means |',
    '|---|---|',
    ...Object.entries(COST_LINE).map(([cost, line]) => `| \`${cost}\` | ${line} |`),
    '',
    '| Name | Cost | Values | Computed from |',
    '|---|---|---|---|',
    ...EVIDENCE_PROVIDERS.map(
      (provider) =>
        `| \`${provider.name}\` | ${provider.cost} | ${cell(provider.values.join(', '))} | ${cell(provider.from)} |`,
    ),
    '',
  ];
  return lines.join('\n');
}

export function run(argv: readonly string[], io = { out: console.log, err: console.error }): number {
  const unknown = argv.filter((arg) => arg !== '--check');
  if (unknown.length > 0) {
    io.err(`unknown argument ${unknown[0]}; usage: tsx tools/docs/blame-reference.ts [--check]`);
    return 2;
  }
  const text = renderBlameReference();
  if (argv.includes('--check')) {
    let current = '';
    try {
      current = readFileSync(BLAME_OUT, 'utf8');
    } catch {
      current = '';
    }
    if (current !== text) {
      io.err('docs/reference/blame.md is stale: run tsx tools/docs/blame-reference.ts');
      return 1;
    }
    io.out('docs/reference/blame.md is current');
    return 0;
  }
  writeFileSync(BLAME_OUT, text);
  io.out('wrote docs/reference/blame.md');
  return 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = run(process.argv.slice(2));
}
